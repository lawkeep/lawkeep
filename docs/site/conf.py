# Markdown copies of every page, for LLMs (published next to the HTML: concepts/laws.md ...)

_INCLUDE = re.compile(r"^```\{include\} (?P<path>\S+)\n(?P<opts>(?::[a-z-]+:.*\n)*)```\n", re.M)
_ADMONITION = re.compile(
    r"^:::\{(?P<kind>note|tip|warning|important|admonition)\}(?P<title>[^\n]*)\n"
    r"(?P<body>.*?)^:::\s*$",
    re.M | re.S,
)
_TOCTREE = re.compile(r"^```\{toctree\}\n.*?^```\n", re.M | re.S)
_LITERAL = re.compile(
    r"^```\{literalinclude\} (?P<path>\S+)\n(?P<opts>(?::[a-z-]+:.*\n)*)```\n", re.M
)


def _expand(text: str, folder: Path) -> str:
    def include(m: re.Match[str]) -> str:
        target = (folder / m.group("path")).resolve()
        body = target.read_text(encoding="utf-8")
        start = re.search(r":start-line: (\d+)", m.group("opts"))
        if start:
            body = "".join(body.splitlines(keepends=True)[int(start.group(1)) :])
        offset = re.search(r":heading-offset: (\d+)", m.group("opts"))
        if offset:
            hashes = "#" * int(offset.group(1))
            body = re.sub(r"^(#{1,6}) ", lambda h: hashes + h.group(1) + " ", body, flags=re.M)
        return _expand(body, target.parent).rstrip("\n") + "\n"

    def literal(m: re.Match[str]) -> str:
        target = (folder / m.group("path")).resolve()
        lang = re.search(r":language: (\S+)", m.group("opts"))
        code = target.read_text(encoding="utf-8").rstrip("\n")
        return f"```{lang.group(1) if lang else 'text'}\n{code}\n```\n"

    def admonition(m: re.Match[str]) -> str:
        kind = m.group("kind")
        title = m.group("title").strip() or kind.capitalize()
        body = m.group("body").strip("\n")
        lines = [f"**{title}:**", "", *body.splitlines()]
        return "\n".join("> " + ln if ln else ">" for ln in lines) + "\n"

    text = _TOCTREE.sub("", text)
    text = _INCLUDE.sub(include, text)
    text = _LITERAL.sub(literal, text)
    return _ADMONITION.sub(admonition, text)


def _write_markdown_copies(app: Any, exception: Exception | None) -> None:
    if exception is not None or app.builder.name not in ("html", "dirhtml"):
        return
    out = Path(app.outdir)
    for docname in sorted(app.env.found_docs):
        source = Path(app.env.doc2path(docname))
        text = _expand(source.read_text(encoding="utf-8"), source.parent)
        target = out / f"{docname}.md"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")


def setup(app: Any) -> dict[str, Any]:
    app.connect("build-finished", _write_markdown_copies)
    return {"parallel_read_safe": True}
